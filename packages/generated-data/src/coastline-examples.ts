export function findSavedExample(
  datasets: DatasetDto[],
  example: CoastlineExample,
) {
  return datasets.find(
    (dataset) =>
      dataset.sha256 === example.sha256 &&
      dataset.name === example.dataset.name &&
      dataset.source === example.dataset.source &&
      (dataset.sourceRevision ?? "") ===
        (example.dataset.sourceRevision ?? "") &&
      dataset.license === example.dataset.license &&
      dataset.crs === example.dataset.crs &&
      dataset.coordinateUnit === example.dataset.coordinateUnit &&
      dataset.pointCount === example.dataset.geometry.coordinates.length,
  );
}
